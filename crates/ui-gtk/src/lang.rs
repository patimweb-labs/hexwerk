/// Unterstuetzte Sprachen.
pub const LANGS: [(&str, &str); 4] = [
    ("de", "Deutsch"),
    ("en", "English"),
    ("es", "Español"),
    ("fr", "Français"),
];

thread_local! {
    /// Die gerade gewaehlte Sprache.
    ///
    /// Warum nicht als Parameter durchreichen: viele Texte entstehen in
    /// freien Funktionen (Zeilen einer Karte, Kurztexte), die keinen Zugriff
    /// auf die Einstellungen haben. Ein zweiter Weg ueber schwache Verweise
    /// waere da unnoetig umstaendlich.
    static CURRENT: std::cell::RefCell<String> = std::cell::RefCell::new(String::new());
}

/// Setzt die Sprache fuer alle Texte, die ohne Parameter entstehen.
pub fn set_current(lang: &str) {
    CURRENT.with(|cell| {
        let mut slot = cell.borrow_mut();
        slot.clear();
        slot.push_str(lang);
    });
}

/// Die gerade gesetzte Sprache; ohne Setzen Deutsch.
pub fn current() -> String {
    CURRENT.with(|cell| {
        let value = cell.borrow();
        if value.is_empty() {
            "de".to_string()
        } else {
            value.clone()
        }
    })
}

/// Text in der aktuell gesetzten Sprache.
pub fn tn(key: &str) -> &'static str {
    t(&current(), key)
}

