/// Wie heisst die Sprache in ihrer eigenen Schreibweise?
pub fn name(code: &str) -> &'static str {
    LANGS
        .iter()
        .find(|(key, _)| *key == code)
        .map(|(_, name)| *name)
        .unwrap_or("Deutsch")
}
